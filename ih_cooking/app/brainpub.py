"""Merge generated recipe sections while retaining hand-written Brain content."""
import hashlib
import json
import re

SECTIONS = ('Steps (minutes before serving)', 'Prep', 'Shopping', 'Equipment')
LINK = re.compile(r'^- \[\[home/recipes/([a-z0-9-]+)\|[^\n]+\]\]$')

class NoteConflict(ValueError):
    pass

def digest(text):
    return hashlib.sha256(text.strip().encode()).hexdigest()

def sections(text):
    matches=list(re.finditer(r'^## (.+)$',text,re.M));out={}
    for index,match in enumerate(matches):
        name=match[1]
        if name not in SECTIONS:continue
        if name in out:raise NoteConflict('duplicate generated section')
        end=matches[index+1].start() if index+1<len(matches) else len(text)
        out[name]=(match.start(),end,text[match.start():end])
    return out

def heading(text):
    match=re.search(r'^# (.+)$',text,re.M)
    if not match:raise NoteConflict('missing recipe heading')
    return match[1]

def generated_line(text):
    lines=[line for line in text.splitlines() if line.startswith(('Generated from `','Generated by the ih_cooking add-on.'))]
    if len(lines)!=1:raise NoteConflict('unrecognized recipe note owner')
    return lines[0]

def same_metadata(old,new):
    oven=lambda s: re.search(r'Oven (.*?)°',s)
    minute=lambda s: re.search(r'(\d+) min before serving',s)
    return bool(oven(old) and oven(new) and minute(old) and minute(new) and oven(old)[1]==oven(new)[1] and minute(old)[1]==minute(new)[1])

def merge_recipe(current,desired,previous):
    target=sections(desired);state={name:digest(target.get(name,(0,0,''))[2]) for name in SECTIONS}
    state.update(heading=heading(desired),metadata=digest(generated_line(desired)))
    if current is None:return desired,state
    old=sections(current);old_heading=heading(current);old_line=generated_line(current);new_line=generated_line(desired)
    for name in SECTIONS:
        actual=digest(old.get(name,(0,0,''))[2]);wanted=state[name]
        if actual!=wanted and actual!=previous.get(name):raise NoteConflict('generated section has unreviewed changes')
    if old_heading not in (state['heading'],previous.get('heading')):raise NoteConflict('recipe heading changed')
    if digest(old_line) not in (state['metadata'],previous.get('metadata')) and not same_metadata(old_line,new_line):raise NoteConflict('recipe metadata changed')
    result=current
    for name,(start,end,_) in sorted(old.items(),key=lambda item:item[1][0],reverse=True):
        replacement=target.get(name,(0,0,''))[2]
        result=result[:start]+(replacement.rstrip()+'\n\n' if replacement else '')+result[end:]
    for name in SECTIONS:
        if name not in old and name in target:result=result.rstrip()+'\n\n'+target[name][2].rstrip()+'\n'
    result=result.replace(old_line,new_line,1)
    result=re.sub(r'^# '+re.escape(old_heading)+r'$',lambda m:'# '+state['heading'],result,count=1,flags=re.M)
    # Only the known generated title property changes; custom front matter is retained.
    expected='Recipe: '+old_heading
    result=re.sub(r'^title: (.+)$',lambda m:'title: '+json.dumps('Recipe: '+state['heading'],ensure_ascii=False) if m[1].strip().strip('"\'')==expected else m[0],result,count=1,flags=re.M)
    return result,state

def merge_index(current,desired):
    if current is None:return desired
    wanted={match[1]:line for line in desired.splitlines() if (match:=LINK.fullmatch(line))}
    if not wanted:return current
    out=[];placed=False
    for line in current.splitlines():
        match=LINK.fullmatch(line)
        if match and match[1] in wanted:
            if not placed:out.extend(wanted.values());placed=True
        else:out.append(line)
    if not placed:out+=['',*wanted.values()]
    result='\n'.join(out).rstrip()+'\n'
    return re.sub(r'Generated by `[^`\n]+`; edit recipes in the recipe builder\.', 'Generated by the IH Cooking add-on; edit recipes in Cooking.', result)
