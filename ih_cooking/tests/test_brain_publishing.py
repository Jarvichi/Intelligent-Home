import io
import json
import pathlib
import sys
import tempfile
import unittest
sys.path.insert(0,str(pathlib.Path(__file__).resolve().parents[1]/'app'))
import brainpub
import cooking
import recipeadmin

class Publishing(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=pathlib.Path(self.tmp.name);(self.root/'recipes').mkdir()
        self.recipe={'title':'Example meal','oven':180,'steps':[{'before':0,'text':'Serve meal'}],'equipment':['Bowl']}
        self.file=self.root/'recipes/example.json';self.file.write_text(json.dumps(self.recipe));self.notes={};self.calls=[];self.fail=False
        def rpc(request,timeout):
            self.assertLessEqual(timeout,3)
            if self.fail:raise OSError('offline')
            message=json.loads(request.data);tool=message['params']['name'];a=message['params']['arguments'];self.calls.append(tool)
            if tool=='brain_read':value=self.notes.get(a['path'],'No such note. Use brain_search or brain_list.')
            else:self.notes[a['path']]=a['content'];value='saved '+a['path']+' (fixture bytes)'
            return io.BytesIO(json.dumps({'result':{'content':[{'type':'text','text':value}]}}).encode())
        self.options={'publish_live':True,'brain_url':'http://brain.invalid/mcp','brain_token':'fixture'}
        self.store=cooking.Store(str(self.root),str(self.root/'no-seed'),self.options,opener=rpc)
    def desired(self):return recipeadmin.brain_notes(str(self.root))['home/recipes/example.md']
    def test_create_then_changed_recipe_and_manual_sections_are_preserved(self):
        self.assertTrue(self.store.publish()['ok']);self.assertEqual(self.calls.count('brain_write'),2)
        path='home/recipes/example.md';self.notes[path]+='\n## Family tips\nKeep this manual advice.\n'
        self.recipe['steps'][0]['text']='Serve carefully';self.file.write_text(json.dumps(self.recipe));self.calls.clear()
        result=self.store.publish();self.assertTrue(result['ok']);self.assertEqual(self.calls.count('brain_write'),1)
        self.assertIn('Serve carefully',self.notes[path]);self.assertIn('Keep this manual advice.',self.notes[path])
        self.calls.clear();self.assertTrue(self.store.publish()['ok']);self.assertNotIn('brain_write',self.calls)
    def test_manual_change_to_generated_section_is_a_conflict(self):
        self.store.publish();path='home/recipes/example.md';self.notes[path]=self.notes[path].replace('Serve meal','Manual instruction')
        old=self.notes[path];self.recipe['steps'][0]['text']='Canonical instruction';self.file.write_text(json.dumps(self.recipe))
        result=self.store.publish();self.assertFalse(result['ok']);self.assertEqual(result['brain']['conflicts'],1);self.assertEqual(self.notes[path],old)
        self.assertEqual(self.store.publication_status()['state'],'review')
    def test_first_adoption_preserves_manual_index_links_and_frontmatter(self):
        desired=self.desired();legacy=desired.replace('Generated by the ih_cooking add-on.','Generated from `recipes/example.json` (edit it in the builder).')
        legacy=legacy.replace('type: note','custom: keep\ntype: note')+'\n## Notes\nA manual note.\n'
        self.notes['home/recipes/example.md']=legacy
        index='---\ntitle: Recipes\nshare: false\n---\n# Recipes\n\nManual intro. Generated by `legacy/publish.py`; edit recipes in the recipe builder.\n- [[home/recipes/example|Old label]]\n\nOther recipes: [[home/recipes/from-notes/from-notes]]\n'
        self.notes['home/recipes/recipes.md']=index
        self.assertTrue(self.store.publish()['ok']);self.assertIn('custom: keep',self.notes['home/recipes/example.md']);self.assertIn('A manual note.',self.notes['home/recipes/example.md'])
        self.assertIn('Manual intro.',self.notes['home/recipes/recipes.md']);self.assertIn('Generated by the IH Cooking add-on',self.notes['home/recipes/recipes.md']);self.assertIn('from-notes/from-notes',self.notes['home/recipes/recipes.md'])
    def test_unknown_or_stale_existing_notes_are_never_overwritten(self):
        for text in ('# Hand-written recipe\nImportant instructions.\n',self.desired().replace('Serve meal','Unreviewed instructions')):
            self.notes['home/recipes/example.md']=text;result=self.store.publish();self.assertFalse(result['ok']);self.assertEqual(self.notes['home/recipes/example.md'],text)
    def test_disabled_publishing_makes_no_requests_and_missing_setup_is_not_success(self):
        self.options['publish_live']=False;self.assertTrue(self.store.publish()['dry']);self.assertEqual(self.calls,[]);self.assertEqual(self.store.publication_status()['state'],'paused')
        self.options['publish_live']=True;self.options['brain_token']='';self.assertFalse(self.store.publish()['ok']);self.assertEqual(self.store.publication_status()['state'],'setup');self.assertEqual(self.calls,[])
    def test_outage_stops_after_first_request_and_safe_status_contains_no_credentials(self):
        self.fail=True;result=self.store.publish();self.assertFalse(result['ok']);self.assertEqual(result['brain']['failed'],2)
        status=self.store.publication_status();self.assertEqual(status['state'],'error');self.assertNotIn('fixture',json.dumps(status));self.assertNotIn('brain.invalid',json.dumps(status))
    def test_removed_equipment_and_renamed_title_preserve_other_sections(self):
        self.store.publish();self.recipe['title']='Renamed meal';self.recipe['equipment']=[];self.file.write_text(json.dumps(self.recipe))
        self.assertTrue(self.store.publish()['ok']);text=self.notes['home/recipes/example.md'];self.assertNotIn('## Equipment',text);self.assertIn('# Renamed meal',text);self.assertIn('title: "Recipe: Renamed meal"',text)
    def test_publisher_rejects_non_recipe_paths_and_other_tools(self):
        for tool,path in [('brain_write','process/private.md'),('brain_append','home/recipes/example.md'),('brain_read','home/recipes/../private.md')]:
            with self.assertRaises(ValueError):self.store._brain_rpc(tool,{'path':path})
        self.assertEqual(self.calls,[])

    def test_empty_write_receipt_does_not_claim_sync(self):
        self.store._brain_rpc=lambda tool,args:{'content':[{'type':'text','text':'No such note.'}]} if tool=='brain_read' else {'content':[]}
        self.assertFalse(self.store.publish()['ok']);self.assertEqual(self.store.publication_status()['state'],'error')

    def test_quoted_titles_and_refused_rpc(self):
        self.recipe['title']='Meal "special"';self.file.write_text(json.dumps(self.recipe));self.assertIn('\\"special\\"',self.desired())
        self.store.opener=lambda *a,**k:io.BytesIO(b'{"result":{"isError":true}}');self.assertFalse(self.store.publish()['ok'])

if __name__=='__main__':unittest.main()
