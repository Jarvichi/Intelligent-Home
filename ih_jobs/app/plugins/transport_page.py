"""transport_page: builds and keeps the read-only "Transport" Home Assistant dashboard (the bus page) from the entities the bus_watch plugin publishes.
It replaces the host script build_rob.py: the page is now generated by this add-on, from IH data only. It never changes the house, only saves one dashboard.
Every house value comes from settings (JSON in the add-on option plugins[].settings); the defaults are generic:
  url_path          dashboard address [transport]; title [Transport]; icon [mdi:bus]; require_admin [false: the family can open it]; theme [House]
  morning_entity    bus_watch morning_entity (sensor, attributes as the old publish scripts: stop, usual, arrives, eta_min, vehicle, deck, note ...). Required.
  home_entity       bus_watch publish_entity (the return journey). Empty = no "bus home" part.
  promise_entity    bus_watch promise_entity (attribute rows, summary, compare). Required.
  schedule_entity   bus_watch schedule_entity (attribute rows {mon..sun: [[stop, 'HH:MM'], ...]}). Empty = no weekly table. Copied into the page when it is built.
  route_label       what the bus is called in sentences ['bus'], e.g. 'no. 30'
  home_prefix       text before a return stop in schedule rows ['Bus home: '] (bus_watch return_row_prefix)
  promise_intro     markdown shown above the promise summary (what was promised and when). Empty = none.
  type_entities     entities for an optional "Record a confirmed bus type" card (inputs and a save button). Empty = no card.
  type_title        title of that card ['Record a confirmed bus type']
The page is rebuilt when its content changes (the schedule, the settings), checked every 30 minutes, and saved only then. Live saves the dashboard through the
Home Assistant websocket (create it if missing, then save its config); dry logs what it would do and writes nothing."""
import hashlib
import json

NAME = 'transport_page'
SCHEDULE = {'kind': 'every', 'minutes': 30}
DEFAULTS = {'url_path': 'transport', 'title': 'Transport', 'icon': 'mdi:bus', 'require_admin': False, 'theme': 'House',
            'morning_entity': '', 'home_entity': '', 'promise_entity': '', 'schedule_entity': '', 'route_label': 'bus', 'home_prefix': 'Bus home: ',
            'promise_intro': '', 'type_entities': [], 'type_title': 'Record a confirmed bus type'}

DAYS = ('mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun')
VERDICT_COLORS = {'kept': 'success', 'broken': 'error', 'unknown': 'muted', 'no_bus': 'warning', 'no_info': 'warning'}
NOTE = ('The sensor only asks the bus feed from 25 minutes before the usual bus until 10 minutes after it, on college days. The time is distance divided by average '
        'speed, not the timetable: expect an error of a few minutes. This page only shows; it changes nothing.')

STATUS_MD = """{% set s = states('ENT') %}{% set a = state_attr('ENT','eta_min') %}
{% if a is not none %}**LEAD is about {{ s }} from {{ state_attr('ENT','stop') }}** (expected {{ state_attr('ENT','arrives') }}; the usual bus is {{ state_attr('ENT','usual') }}).
Last seen near {{ state_attr('ENT','last_seen_near') }}, {{ state_attr('ENT','km_away') }} km along the route, GPS {{ state_attr('ENT','data_age_min') }} min old.
{% if state_attr('ENT','deck') %}Deck: {{ state_attr('ENT','deck') }}.{% endif %}
{% elif s == 'No live data' %}**No live data.** {{ state_attr('ENT','note') }}, last seen near {{ state_attr('ENT','last_seen_near') }}. Do not trust a time.
{% elif s == 'No bus yet' %}**No bus on the road yet** before {{ state_attr('ENT','stop') }}.
{% elif s == 'No data' %}**The bus feed is not answering.** {{ state_attr('ENT','note') }}
{% elif s == 'Off' %}**Not watching for a bus right now.** {{ state_attr('ENT','note') }}.
{% else %}**{{ s }}.** {{ state_attr('ENT','note') }}{% endif %}"""


def _hide_off(entity):
    return [{'condition': 'state', 'entity': entity, 'state_not': 'Off'}, {'condition': 'state', 'entity': entity, 'state_not': 'unavailable'}]


def _status_md(entity, lead):
    return STATUS_MD.replace('ENT', entity).replace('LEAD', lead)


def _journey_cards(entity, name, lead, route, with_direction):
    vis = _hide_off(entity)
    attrs = [('stop', 'Stop'), ('usual', 'Usual bus'), ('arrives', 'Expected at stop')] + ([('direction', 'Direction')] if with_direction else []) + [('vehicle', 'Bus')]
    rows = [{'type': 'attribute', 'entity': entity, 'attribute': a, 'name': n} for a, n in attrs]
    rows.append({'type': 'attribute', 'entity': entity, 'attribute': 'updated', 'name': 'Checked', 'format': 'relative'})
    return [{'type': 'tile', 'entity': entity, 'name': name + ' status', 'icon': 'mdi:bus-clock', 'vertical': False, 'features_position': 'bottom', 'visibility': vis},
            {'type': 'markdown', 'content': _status_md(entity, lead), 'visibility': vis},
            {'type': 'entities', 'title': 'Details' if name == 'Bus' else 'Details (%s)' % name.lower(), 'visibility': vis, 'entities': rows}]


def week_rows(sched, prefix):
    """Table rows from the schedule entity's rows {mon..sun: [[stop, 'HH:MM'], ...]}; a stop starting with `prefix` is the way home."""
    out = []
    for day in DAYS:
        for i, item in enumerate((sched or {}).get(day) or []):
            if not isinstance(item, (list, tuple)) or len(item) < 2:
                continue
            stop, time = str(item[0]), str(item[1])
            home = bool(prefix) and stop.startswith(prefix)
            out.append({'id': '%s-%d' % (day, i), 'day': day.title(), 'journey': 'To home' if home else 'To college', 'stop': stop[len(prefix):] if home else stop, 'time': time})
    return out


def _week_card(rows):
    return {'type': 'custom:house-table-card', 'title': 'Usual weekly buses', 'rows': rows, 'row_key': 'id', 'search_placeholder': 'Filter stops or times...',
            'chips': ['journey'], 'chip_order': {'journey': ['To college', 'To home']}, 'filter_selects': True, 'sort': {'key': 'day', 'dir': 'asc'},
            'empty': 'No buses scheduled', 'narrow_width': 720,
            'columns': [{'key': 'day', 'label': 'Day'}, {'key': 'journey', 'label': 'Journey', 'type': 'badge', 'colors': {'To college': 'info', 'To home': 'accent'}},
                        {'key': 'stop', 'label': 'Stop', 'grow': True}, {'key': 'time', 'label': 'Usual bus', 'type': 'date'}]}


def _history_card(entity):
    """One table of every recorded journey (morning and return), filterable by journey, result and day type."""
    return {'type': 'custom:house-table-card', 'title': 'Journey history', 'entity': entity, 'attribute': 'rows', 'row_key': 'id', 'search_placeholder': 'Filter journeys...',
            'chips': ['label'], 'filter_selects': True, 'sort': {'key': 'date', 'dir': 'desc'}, 'empty': 'No journeys recorded yet', 'max_height': 560, 'narrow_width': 720,
            'columns': [{'key': 'date', 'label': 'Date', 'type': 'date', 'fmt': 'short'}, {'key': 'text', 'label': 'Journey', 'grow': True},
                        {'key': 'bus', 'label': 'Bus', 'narrow': 'hide'},
                        {'key': 'label', 'label': 'Result', 'type': 'badge', 'color_key': 'verdict', 'colors': VERDICT_COLORS},
                        {'key': 'verdict', 'hidden': True}, {'key': 'journey', 'hidden': True}, {'key': 'id', 'hidden': True}]}


def build_config(s, schedule_rows=None):
    """The whole dashboard config for settings `s` (pure: no network). schedule_rows = the schedule entity's rows attribute (or None)."""
    route = s['route_label']
    out = {'title': s['title'], 'views': []}
    left = [{'type': 'grid', 'heading': 'College bus', 'icon': 'mdi:bus-clock', 'cards': _journey_cards(s['morning_entity'], 'Bus', 'The %s' % route, route, True)}]
    if s['home_entity']:
        left.append({'type': 'grid', 'heading': 'Bus home', 'icon': 'mdi:bus-clock',
                     'cards': _journey_cards(s['home_entity'], 'Bus home', 'Your bus home (the %s)' % route, route, False)})
    if s['schedule_entity']:
        left.append({'type': 'grid', 'heading': 'This week', 'icon': 'mdi:calendar-week', 'column_span': 2,
                     'cards': [_week_card(week_rows(schedule_rows, s['home_prefix'])), {'type': 'markdown', 'content': NOTE}]})
    out['views'].append({'title': 'College bus', 'path': 'college-bus', 'icon': 'mdi:bus', 'type': 'sections', 'max_columns': 2, 'sections': left, 'theme': s['theme']})
    cards = []
    if s['promise_intro']:
        cards.append({'type': 'markdown', 'content': str(s['promise_intro'])})
    cards.append({'type': 'markdown', 'content': "{{ state_attr('%s','summary') }}" % s['promise_entity']})
    cards.append(_history_card(s['promise_entity']))
    cards.append({'type': 'markdown', 'content': 'The return buses (home to the first stop, about 15 minutes after a lesson) are shown for comparison and are not counted in the percentage above.'})
    if s['type_entities']:
        cards.append({'type': 'entities', 'title': s['type_title'], 'entities': list(s['type_entities'])})
    out['views'].append({'title': 'Double-decker promise', 'path': 'double-decker', 'icon': 'mdi:bus-double-decker', 'type': 'sections', 'max_columns': 2,
                         'sections': [{'type': 'grid', 'heading': 'Double-decker promise', 'icon': 'mdi:bus-double-decker', 'column_span': 2, 'cards': cards}], 'theme': s['theme']})
    return out


def digest(cfg):
    return hashlib.sha256(json.dumps(cfg, sort_keys=True).encode()).hexdigest()


def run(ctx):
    s = ctx.settings
    need = [k for k in ('morning_entity', 'promise_entity') if not s.get(k)]
    if need:
        ctx.log('not configured (needs %s in settings)' % ', '.join(need))
        return False
    rows = None
    if s['schedule_entity']:
        try:
            rows = ((ctx.ha.get('states/' + s['schedule_entity']) or {}).get('attributes') or {}).get('rows')
        except Exception as e:
            ctx.log('could not read %s (%s); keeping the weekly table out of this build' % (s['schedule_entity'], type(e).__name__))
            return False
    cfg = build_config(s, rows)
    h = digest(cfg)
    st = ctx.state.load('state')
    if st.get('digest') == h:
        ctx.log('page unchanged, nothing to save')
        return True
    if ctx.dry:
        ctx.log('[DRY] would save dashboard %s (%d views, digest %s)' % (s['url_path'], len(cfg['views']), h[:8]))
        return True
    listed = ctx.ha.ws({'type': 'lovelace/dashboards/list'}) or []
    if not any(d.get('url_path') == s['url_path'] for d in listed):
        ctx.ha.ws({'type': 'lovelace/dashboards/create', 'url_path': s['url_path'], 'title': s['title'], 'icon': s['icon'],
                   'require_admin': bool(s['require_admin']), 'show_in_sidebar': True, 'mode': 'storage'})
        ctx.log('created dashboard %s' % s['url_path'])
    ctx.ha.ws({'type': 'lovelace/config/save', 'url_path': s['url_path'], 'config': cfg})
    ctx.state.save('state', {'digest': h, 'saved_at': ctx.now.isoformat(timespec='seconds')})
    ctx.log('saved dashboard %s (digest %s)' % (s['url_path'], h[:8]))
    return True
